#!/usr/bin/env python3
"""Packs the recorded start-card lines (tools/voci/intro-clips/<lang>/<chapter>_<i>.mp3, made by tools/voci/intro_split.py)
into src/018-intro-voci.js. The lines and who says them are in tools/voci/intro.py and in STR 'lvl.<key>.talk'.
Run from the repo root: python3 tools/pack-intro.py"""
import base64, json, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), 'voci'))
import intro as I
root = os.path.join(os.path.dirname(__file__), 'voci', 'intro-clips')
data = {}
for lang in ('ro', 'en'):
    data[lang] = {}
    for key, L in I.INTRO:
        data[lang][key] = [{'w': 0 if w == 'b' else 1, 'd': base64.b64encode(open(os.path.join(root, lang, f'{key}_{i}.mp3'), 'rb').read()).decode()}
                           for i, (w, *_rest) in enumerate(L)]
js = ('/* Generated by tools/pack-intro.py from tools/voci/intro-clips. Do not edit.\n'
      '   The start card of each chapter, said by the heroes: INTRO_VOICE[lang][chapter key] = [{ w: 0 Boon / 1 Killer, d: mp3 in base64 }],\n'
      '   one per line of STR lvl.<key>.talk, in order. */\n'
      'const INTRO_VOICE = ' + json.dumps(data, separators=(',', ':')) + ';\n')
open(os.path.join(os.path.dirname(__file__), '..', 'src', '018-intro-voci.js'), 'w').write(js)
print('src/018-intro-voci.js', len(js) // 1024, 'KB')
