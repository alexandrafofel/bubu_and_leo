#!/usr/bin/env python3
"""Packs the Krea pictures from art/krea/*.png into src/016-art-data.js (one const ART_DATA: name -> data URI).
Before packing, every dull pixel gets a little color and the darkest ones a deep violet: the game has no grey and no black (CLAUDE.md, rule 4).
Run it after adding or changing a picture in art/krea, then ./build.sh. See docs/05-pictura.md, "Imaginile Krea"."""
import base64, colorsys, glob, io, os, sys
from PIL import Image
import numpy as np
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def degrey(im):
    """No grey and no black (rule 4): a dull pixel keeps its own hue but gets at least a little color; a pixel with no hue
    at all gets the warm violet of the shadows; the darkest ones are lifted to a deep violet. Light pixels stay as they are."""
    rgba = im.convert('RGBA'); alpha = rgba.getchannel('A')
    h, s_, v = [np.asarray(ch).astype(np.int32) for ch in rgba.convert('RGB').convert('HSV').split()]
    dull = v < 200
    nohue = dull & (s_ < 14)
    h = np.where(nohue, 205, h)                                     # 205/255 of the color wheel: violet
    s_ = np.where(dull, np.maximum(s_, 72), s_)                     # at least 28 % color
    v = np.where(v < 80, 80 + (v * 0.25).astype(np.int32), v)       # no black
    hsv = Image.merge('HSV', [Image.fromarray(x.clip(0, 255).astype(np.uint8), 'L') for x in (h, s_, v)])
    out = hsv.convert('RGB').convert('RGBA'); out.putalpha(alpha)
    return out
out = ['// GENERATED by tools/pack-art.py from art/krea/*.png. Do not edit: change the pictures and run the script again.',
       '// The Krea pictures of the new look (docs/05-pictura.md, "Imaginile Krea"). Each one is a WebP with transparency.',
       'const ART_DATA = {']
tot = 0
for f in sorted(glob.glob(os.path.join(ROOT, 'art/krea/*.png'))):
    n = os.path.basename(f)[:-4]; b = io.BytesIO()
    degrey(Image.open(f)).save(b, 'WEBP', quality=84, method=6); d = b.getvalue(); tot += len(d)
    out.append("  '%s': 'data:image/webp;base64,%s'," % (n, base64.b64encode(d).decode()))
out.append('};')
open(os.path.join(ROOT, 'src/016-art-data.js'), 'w').write('\n'.join(out) + '\n')
print('packed', len(out) - 4, 'pictures,', tot // 1024, 'KB')
