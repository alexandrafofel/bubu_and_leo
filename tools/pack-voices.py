#!/usr/bin/env python3
"""T13: packs the voice clips (tools/voci/clips/<hero>/NN_key.mp3) into src/017-voci-data.js.
The order of the lines in tools/voci/catalog.py is the id of each word (never changes: saves keep the ids).
Run from the repo root: python3 tools/pack-voices.py"""
import base64, json, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), 'voci'))
import catalog as c
root = os.path.join(os.path.dirname(__file__), 'voci', 'clips')
heroes = []
for name, lines in (('boon', c.BOON), ('killer', c.KILLER)):
    out = []
    for i, (key, say, ro, en) in enumerate(lines):
        p = os.path.join(root, name, f'{i:02d}_{key}.mp3')
        d = base64.b64encode(open(p, 'rb').read()).decode()
        out.append({'k': key, 'say': say, 'ro': ro, 'en': en, 'd': d})
    heroes.append(out)
js = ('/* Generated by tools/pack-voices.py from tools/voci/clips/*.mp3. Do not edit.\n'
      '   The voices of Boon (a small child playing a dinosaur) and Killer: one short clip per line, mp3 in base64.\n'
      '   VOICE_DATA.lupta[0] = Boon, [1] = Killer. The position in the list is the id of the word. */\n'
      'const VOICE_DATA = { lupta: ' + json.dumps(heroes, ensure_ascii=False, separators=(',', ':')) + ' };\n')
open(os.path.join(os.path.dirname(__file__), '..', 'src', '017-voci-data.js'), 'w').write(js)
print('src/017-voci-data.js', len(js) // 1024, 'KB')
